/**
 * Vendors the official Mastra skills (github.com/mastra-ai/skills) into
 * src/server/mcp/official-skills.generated.ts, which the built-in MCP server serves over the
 * MCP Skills extension. Run `pnpm --filter ./packages/server sync:mastra-skills [ref]` to update.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'https://github.com/mastra-ai/skills.git';
const ref = process.argv[2] ?? 'main';
const output = join(dirname(fileURLToPath(import.meta.url)), '../src/server/mcp/official-skills.generated.ts');

const checkout = mkdtempSync(join(tmpdir(), 'mastra-skills-'));
try {
  execFileSync('git', ['clone', '--quiet', '--depth', '1', '--branch', ref, REPO, checkout], { stdio: 'inherit' });
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: checkout, encoding: 'utf8' }).trim();
  const root = join(checkout, 'skills');

  const files: Record<string, string> = {};
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.isFile()) {
        const bytes = readFileSync(path);
        const text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
        files[relative(root, path).split('\\').join('/')] = text;
      }
    }
  };
  walk(root);

  const skills = Object.keys(files).filter(path => path.endsWith('/SKILL.md'));
  if (skills.length === 0) throw new Error(`No skills found under skills/ in ${REPO}@${ref}`);

  writeFileSync(
    output,
    `// Generated by scripts/sync-mastra-skills.ts from ${REPO.replace(/\.git$/, '')} at ${commit}. Do not edit.\n` +
      `/* eslint-disable */\n\n` +
      `export const OFFICIAL_SKILLS_SOURCE = ${JSON.stringify({ repository: REPO.replace(/\.git$/, ''), commit })} as const;\n\n` +
      `export const OFFICIAL_SKILL_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)};\n`,
  );
  console.log(`Wrote ${Object.keys(files).length} files (${skills.join(', ')}) from ${commit} to ${output}`);
} finally {
  rmSync(checkout, { recursive: true, force: true });
}
