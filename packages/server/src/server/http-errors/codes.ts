/**
 * Business error codes exposed on the `problem.code` member of error responses.
 *
 * Codes only exist when they add business meaning a frontend can act on
 * ("which thing was not found", "why was it a conflict").
 */
export const MASTRA_ERROR_CODES = {
  // Agents
  AGENT_NOT_FOUND: 'AGENT_NOT_FOUND',
  MODEL_NOT_ALLOWED: 'MODEL_NOT_ALLOWED',
  NO_MODEL_SELECTED: 'NO_MODEL_SELECTED',

  // Workflows
  WORKFLOW_NOT_FOUND: 'WORKFLOW_NOT_FOUND',
  WORKFLOW_RUN_NOT_FOUND: 'WORKFLOW_RUN_NOT_FOUND',
  WORKFLOW_RUN_ACCESS_DENIED: 'WORKFLOW_RUN_ACCESS_DENIED',
  WORKFLOW_SCHEMA_VALIDATION_FAILED: 'WORKFLOW_SCHEMA_VALIDATION_FAILED',
  WORKFLOW_RESUME_ALREADY_CLAIMED: 'WORKFLOW_RESUME_ALREADY_CLAIMED',

  // Runs (shared)
  RUN_ID_REQUIRED: 'RUN_ID_REQUIRED',

  // Durable agent runs
  DURABLE_RUN_ACTIVE: 'DURABLE_RUN_ACTIVE',
  DURABLE_RUN_RECOVERY_IN_PROGRESS: 'DURABLE_RUN_RECOVERY_IN_PROGRESS',
  DURABLE_RUN_SUSPENDED: 'DURABLE_RUN_SUSPENDED',
  DURABLE_RUN_EXECUTION_CONFLICT: 'DURABLE_RUN_EXECUTION_CONFLICT',
  DURABLE_RUN_ACCESS_DENIED: 'DURABLE_RUN_ACCESS_DENIED',

  // Memory
  THREAD_NOT_FOUND: 'THREAD_NOT_FOUND',
  THREAD_ACCESS_DENIED: 'THREAD_ACCESS_DENIED',

  // Other resources
  TOOL_NOT_FOUND: 'TOOL_NOT_FOUND',
  PROCESSOR_NOT_FOUND: 'PROCESSOR_NOT_FOUND',
  WORKSPACE_NOT_FOUND: 'WORKSPACE_NOT_FOUND',
  SCHEDULE_NOT_FOUND: 'SCHEDULE_NOT_FOUND',
  BACKGROUND_TASK_NOT_FOUND: 'BACKGROUND_TASK_NOT_FOUND',
  PLAN_CAPABILITY_NOT_FOUND: 'PLAN_CAPABILITY_NOT_FOUND',

  // Storage
  STORAGE_NOT_CONFIGURED: 'STORAGE_NOT_CONFIGURED',
  STORAGE_DOMAIN_UNAVAILABLE: 'STORAGE_DOMAIN_UNAVAILABLE',

  // Observability
  OBSERVABILITY_FEATURE_NOT_IMPLEMENTED: 'OBSERVABILITY_FEATURE_NOT_IMPLEMENTED',
  FEEDBACK_REVIEW_STATUS_CONFLICT: 'FEEDBACK_REVIEW_STATUS_CONFLICT',

  // Request validation
  INVALID_REQUEST_BODY: 'INVALID_REQUEST_BODY',
  INVALID_QUERY_PARAMS: 'INVALID_QUERY_PARAMS',
  INVALID_PATH_PARAMS: 'INVALID_PATH_PARAMS',
} as const;

export type MastraErrorCode = (typeof MASTRA_ERROR_CODES)[keyof typeof MASTRA_ERROR_CODES];

export function isMastraErrorCode(value: unknown): value is MastraErrorCode {
  return typeof value === 'string' && Object.prototype.hasOwnProperty.call(MASTRA_ERROR_CODES, value);
}
