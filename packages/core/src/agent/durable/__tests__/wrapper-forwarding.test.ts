const agentMembers = Object.getOwnPropertyNames(Agent.prototype).filter(name => name !== 'constructor');
const wrapperMembers = new Set(Object.getOwnPropertyNames(DurableAgent.prototype));

describe('DurableAgent forwarding', () => {
  it('forwards every Agent member or lists it as running on the wrapper', () => {
    // A new Agent member must be either overridden in DurableAgent to read from the wrapped
    // agent, or added to RUNS_ON_WRAPPER. Otherwise wrappers silently serve stale configuration.
    const unclassified = agentMembers.filter(name => !wrapperMembers.has(name) && !RUNS_ON_WRAPPER.has(name));
    expect(unclassified).toEqual([]);
  });

  it('keeps RUNS_ON_WRAPPER limited to inherited Agent members', () => {
    const stale = [...RUNS_ON_WRAPPER].filter(name => !agentMembers.includes(name) || wrapperMembers.has(name));
    expect(stale).toEqual([]);
  });
});
