/**
 * What the widget editor offers to chart. Each entry knows where its numbers come from and how they
 * can be aggregated, so the form never asks for a source, a request or a format.
 */

export type EditorKind = 'kpis' | 'line' | 'stackedBar' | 'table' | 'scores';

export const EDITOR_KINDS: { value: EditorKind; label: string }[] = [
  { value: 'kpis', label: 'KPI' },
  { value: 'line', label: 'Line' },
  { value: 'stackedBar', label: 'Stacked bars' },
  { value: 'table', label: 'Table' },
  { value: 'scores', label: 'Scores' },
];

export const isTimeseriesKind = (kind: EditorKind) => kind === 'line' || kind === 'stackedBar';

export type Aggregation = 'sum' | 'count' | 'avg' | 'min' | 'max' | 'p50' | 'p95' | 'p99';

export const AGGREGATION_LABELS: Record<Aggregation, string> = {
  sum: 'Sum',
  count: 'Count',
  avg: 'Average',
  min: 'Min',
  max: 'Max',
  p50: 'P50',
  p95: 'P95',
  p99: 'P99',
};

export const PERCENTILES: Partial<Record<Aggregation, number>> = { p50: 0.5, p95: 0.95, p99: 0.99 };
export const isPercentile = (aggregation: Aggregation | undefined) =>
  aggregation !== undefined && aggregation in PERCENTILES;
/** Aggregations whose values add up across groups and buckets. */
export const isAdditive = (aggregation: Aggregation | undefined) => aggregation === 'sum' || aggregation === 'count';

export const METRIC_GROUPS = ['Usage', 'Cost', 'Performance', 'Quality'] as const;
export type MetricGroup = (typeof METRIC_GROUPS)[number];

type EntryBase = { id: string; label: string; group: MetricGroup; description: string };

export type MetricsEntry = EntryBase & {
  source: 'metrics';
  format: Extract<ValueFormat, 'count' | 'usd' | 'duration'>;
  names: [string, ...string[]];
  /** Cost reads the tokens' estimated cost rather than their value. */
  field?: 'estimatedCost';
  /** The first is the default. */
  aggregations: [Aggregation, ...Aggregation[]];
};

/** Failed runs over all runs, from one duration metric grouped by status. */
export type ErrorRateEntry = EntryBase & { source: 'errorRate'; format: 'percent'; name: string };

export type ScoreEntry = EntryBase & { source: 'scores'; format: 'score'; scorerId: string };

export type CatalogueEntry = MetricsEntry | ErrorRateEntry | ScoreEntry;

