/** Run statuses that count as failed; observability writes `error`, older runs `failed`. */
export const FAILED_STATUSES = ['error', 'failed'];

export const scoreEntryId = (scorerId: string) => `score:${scorerId}`;

export const scoreEntry = (scorer: Scorer): ScoreEntry => ({
  id: scoreEntryId(scorer.scorerId),
  label: scorer.name,
  group: 'Quality',
  description: `Average ${scorer.name} score.`,
  source: 'scores',
  format: 'score',
  scorerId: scorer.scorerId,
});

/** The static entries plus one per scorer. */
export function catalogue(scorers: readonly Scorer[]): CatalogueEntry[] {
  return [...STATIC_ENTRIES, ...scorers.map(scoreEntry)];
}

/** An entry by id; a scorer that wasn't discovered still resolves, named by its id. */
export function findEntry(id: string, scorers: readonly Scorer[]): CatalogueEntry | undefined {
  const known = STATIC_ENTRIES.find(e => e.id === id);
  if (known) return known;
  if (!id.startsWith('score:')) return undefined;
  const scorerId = id.slice('score:'.length);
  return scoreEntry(scorers.find(s => s.scorerId === scorerId) ?? { scorerId, name: scorerId });
}

/**
 * The aggregations an entry offers in a kind; `undefined` when the kind can't show the entry at all,
 * and an empty list when it can but there's nothing to pick.
 */
export function aggregationsFor(entry: CatalogueEntry, kind: EditorKind): readonly Aggregation[] | undefined {
  switch (entry.source) {
    case 'scores':
      return kind === 'scores' || kind === 'line' ? [] : undefined;
    case 'errorRate':
      return isTimeseriesKind(kind) ? [] : undefined;
    case 'metrics': {
      if (kind === 'scores') return undefined;
      if (kind === 'kpis') return entry.format === 'duration' ? undefined : entry.aggregations;
      if (kind === 'table') {
        const allowed = entry.aggregations.filter(a => !isPercentile(a));
        return allowed.length ? allowed : undefined;
      }
      return entry.aggregations;
    }
  }
}

export const defaultAggregation = (entry: CatalogueEntry): Aggregation | undefined =>
  entry.source === 'metrics' ? entry.aggregations[0] : undefined;

