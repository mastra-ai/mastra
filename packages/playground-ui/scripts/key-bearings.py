"""Writes src/ds/components/Kbd/key-bearings.ts: how far each character's ink sits from the edges of its advance width.

Run after changing a file in fonts/: uv run scripts/key-bearings.py
"""

import subprocess
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).parent.parent
OUTPUT = ROOT / "src/ds/components/Kbd/key-bearings.ts"
CHARACTERS = range(0x21, 0x7F)


def bearings(font):
    glyphs, cmap, upm = font.getGlyphSet(), font.getBestCmap(), font["head"].unitsPerEm
    left, right = [], []
    for character in CHARACTERS:
        glyph = glyphs[cmap[character]]
        pen = BoundsPen(glyphs)
        glyph.draw(pen)
        left.append(round(pen.bounds[0] / upm, 3))
        right.append(round((glyph.width - pen.bounds[2]) / upm, 3))
    return left, right


def load(name):
    return TTFont(ROOT / "fonts" / f"{name}.woff2")


# The body face is variable: shortcuts use it between the normal (465) and medium (515) weights.
faces = {
    "mono": load("commit-mono-latin-400-normal"),
    "monoBold": load("commit-mono-latin-700-normal"),
    "body": instantiateVariableFont(load("mona-sans-latin-standard-normal"), {"wght": 490, "wdth": 100}),
}

lines = [
    "// Generated by scripts/key-bearings.py. Don't edit.",
    "",
    "// Side bearings in em, from ! to ~, of the fonts in fonts/.",
    "export const keyBearings = {",
]
for name, font in faces.items():
    left, right = bearings(font)
    lines += [f"  {name}: {{", f"    left: {left},", f"    right: {right},", "  },"]
lines.append("} as const;")

OUTPUT.write_text("\n".join(lines) + "\n")
subprocess.run(["pnpm", "exec", "oxfmt", str(OUTPUT)], check=True, cwd=ROOT)
