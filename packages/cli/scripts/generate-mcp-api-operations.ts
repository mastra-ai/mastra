import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { Command } from 'commander';
import { format } from 'oxfmt';
import type { FormatConfig } from 'oxfmt';

import { API_COMMANDS, registerApiCommand } from '../src/commands/api/index.js';

const executionCommands = new Set([
  'agent run',
  'workflow run start',
  'workflow run resume',
  'tool execute',
  'mcp tool execute',
  'experiment run',
]);

export const outputPath = path.resolve(import.meta.dirname, '../../mcp/src/server/mastra-api-operations.generated.ts');

export function getOperations() {
  registerApiCommand(new Command());

  // The MCP requester supports API-prefixed server routes, not origin-relative Factory/platform routes.
  return Object.values(API_COMMANDS)
    .filter(command => (command.routePlacement ?? 'api-prefix') === 'api-prefix')
    .map(command => ({
      name: command.name.replaceAll(' ', '_').replaceAll('-', '_'),
      description: command.description,
      method: command.method,
      path: command.path,
      ...(command.verbose ? { verbosePath: command.verbose.path } : {}),
      // Generic execution can invoke arbitrary user code with destructive side effects.
      destructive:
        executionCommands.has(command.name) || command.name.includes(' delete') || command.name.includes(' cancel'),
    }));
}

export async function generateOperationsSource() {
  const output = `// This file is generated by packages/cli/scripts/generate-mcp-api-operations.ts. Do not edit by hand.
// Scope: API-prefixed Mastra server CLI commands only; origin-relative Factory/platform commands are excluded.

export const MASTRA_API_OPERATIONS = ${JSON.stringify(getOperations(), null, 2)} as const;
`;
  const config = JSON.parse(
    await readFile(path.resolve(import.meta.dirname, '../../../.oxfmtrc.json'), 'utf8'),
  ) as FormatConfig;
  const result = await format(outputPath, output, config);
  if (result.errors.length > 0) {
    throw new Error(`Failed to format MCP API operations: ${JSON.stringify(result.errors)}`);
  }
  return result.code;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  await writeFile(outputPath, await generateOperationsSource());
}
