/**
 * Writes `src/event-payloads/event-types.generated.ts`: every provider and
 * event type in `ConnectEventPayloads`, as runtime lists. The events filter
 * uses them so a typed provider only delivers events whose payload type is
 * known.
 *
 * TypeScript 7 has no compiler API, so this reads the keys from the
 * "missing properties" error tsc reports with `--noErrorTruncation`.
 *
 * Run it after changing a payload map: `pnpm --filter @mastra/connect generate:event-types`.
 */
import { spawnSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = join(PACKAGE_DIR, 'src/event-payloads/event-types.generated.ts');
/** Runs tsc on `source` and returns the keys of each probed object type, by probe name. */
async function probe(source: string): Promise<Map<string, string[]>> {
  // Unique per call, so concurrent runs don't overwrite each other's probe.
  const id = randomUUID();
  const probeFile = join(PACKAGE_DIR, `type-tests/event-types-probe-${id}.ts`);
  const probeConfig = join(PACKAGE_DIR, `tsconfig.event-types-probe-${id}.json`);
  try {
    await writeFile(probeFile, source);
    await writeFile(probeConfig, JSON.stringify({ extends: './tsconfig.json', include: [], files: [probeFile] }));
    const result = spawnSync(
      'pnpm',
      ['exec', 'tsc', '--noEmit', '--noErrorTruncation', '--pretty', 'false', '-p', probeConfig],
      {
        cwd: PACKAGE_DIR,
        encoding: 'utf8',
      },
    );
    const output = result.stdout + result.stderr;
    const keys = new Map<string, string[]>();
    const lines = source.split('\n');
    for (const [line, row] of output.matchAll(/^.*\((\d+),\d+\): error TS27(?:39|40|41): .*$/gm)) {
      const name = /export const (\w+)/.exec(lines[Number(row) - 1] ?? '')?.[1];
      const type = /'\{ (.*) \}'/.exec(line)?.[1];
      if (!name || type === undefined) continue;
      keys.set(
        name,
        [...type.matchAll(/(?:"((?:[^"\\]|\\.)*)"|'([^']*)'|([A-Za-z_$][\w$]*)): 0;/g)].map(
          ([, quoted, single, bare]) =>
            quoted !== undefined ? (JSON.parse(`"${quoted}"`) as string) : (single ?? bare!),
        ),
      );
    }
    if (keys.size === 0) throw new Error(`tsc reported no keys:\n${output}`);
    return keys;
  } finally {
    await rm(probeFile, { force: true });
    await rm(probeConfig, { force: true });
  }
}

const IMPORT = "import type { ConnectEventPayloads } from '../src/event-payloads/index.js';\n";

async function main(): Promise<void> {
  const providers = (
    await probe(`${IMPORT}export const providers: { [P in keyof ConnectEventPayloads]: 0 } = {};\n`)
  ).get('providers');
  if (!providers) throw new Error('Could not read the providers of ConnectEventPayloads.');

  const probes = providers.map(
    (provider, index) =>
      `export const p${index}: { [E in Extract<keyof ConnectEventPayloads[${JSON.stringify(provider)}], string>]: 0 } = {};`,
  );
  const keys = await probe(`${IMPORT}${probes.join('\n')}\n`);

  const entries = providers.map((provider, index) => {
    const types = keys.get(`p${index}`);
    if (!types?.length) throw new Error(`Could not read the event types of ${provider}.`);
    return `  ${JSON.stringify(provider)}: ${JSON.stringify([...types].sort())},`;
  });

  const code = `// This file is generated by \`pnpm generate:event-types\`. Do not edit it.

import type { ConnectEventPayloads } from './index.js';

/**
 * Every event type with a typed payload, by provider. A typed provider only
 * delivers these, so a delivered event's payload always has a type.
 */
export const connectEventTypes = {
${entries.join('\n')}
} as const satisfies { readonly [P in keyof ConnectEventPayloads]?: readonly Extract<keyof ConnectEventPayloads[P], string>[] };
`;
  const previous = await readFile(OUT_FILE, 'utf8').catch(() => undefined);
  await writeFile(OUT_FILE, code);
  // Formatted the way the repo's `lint:format` check expects.
  const format = spawnSync('pnpm', ['exec', 'oxfmt', OUT_FILE], { stdio: 'inherit' });
  if (format.status !== 0) throw new Error('oxfmt failed on the generated event types');
  const formatted = await readFile(OUT_FILE, 'utf8');
  console.info(
    `${previous === formatted ? 'unchanged' : 'wrote'} src/event-payloads/event-types.generated.ts (${providers.length} providers)`,
  );
}

await main();
