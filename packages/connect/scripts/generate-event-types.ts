/**
 * Writes `src/event-payloads/event-types.generated.ts`: every provider and
 * event type in `ConnectEventPayloads`, as runtime lists. The events filter
 * uses them so a typed provider only delivers events whose payload type is
 * known.
 *
 * TypeScript 7 has no compiler API, so this reads the keys from the
 * "missing properties" error tsc reports with `--noErrorTruncation`.
 *
 * Run it after changing a payload map: `pnpm --filter @mastra/connect generate:event-types`.
 */
import { spawnSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = join(PACKAGE_DIR, 'src/event-payloads/event-types.generated.ts');
/** Runs tsc on `source` and returns the keys of each probed object type, by probe name. */
async function probe(source: string): Promise<Map<string, string[]>> {
  // Unique per call, so concurrent runs don't overwrite each other's probe.
  const id = randomUUID();
  const probeFile = join(PACKAGE_DIR, `type-tests/event-types-probe-${id}.ts`);
  const probeConfig = join(PACKAGE_DIR, `tsconfig.event-types-probe-${id}.json`);
  try {
    await writeFile(probeFile, source);
    await writeFile(probeConfig, JSON.stringify({ extends: './tsconfig.json', include: [], files: [probeFile] }));
    const result = spawnSync(
      'pnpm',
      ['exec', 'tsc', '--noEmit', '--noErrorTruncation', '--pretty', 'false', '-p', probeConfig],
      {
        cwd: PACKAGE_DIR,
        encoding: 'utf8',
      },
    );
    const output = result.stdout + result.stderr;
    const keys = new Map<string, string[]>();
    const lines = source.split('\n');
    for (const [line, row] of output.matchAll(/^.*\((\d+),\d+\): error TS27(?:39|40|41): .*$/gm)) {
      const name = /export const (\w+)/.exec(lines[Number(row) - 1] ?? '')?.[1];
      const type = /'\{ (.*) \}'/.exec(line)?.[1];
      if (!name || type === undefined) continue;
      keys.set(
        name,
        [...type.matchAll(/(?:"((?:[^"\\]|\\.)*)"|'([^']*)'|([A-Za-z_$][\w$]*)): 0;/g)].map(
          ([, quoted, single, bare]) =>
            quoted !== undefined ? (JSON.parse(`"${quoted}"`) as string) : (single ?? bare!),
        ),
      );
    }
    if (keys.size === 0) throw new Error(`tsc reported no keys:\n${output}`);
    return keys;
  } finally {
    await rm(probeFile, { force: true });
    await rm(probeConfig, { force: true });
  }
}

const IMPORT = "import type { ConnectEventPayloads } from '../src/event-payloads/index.js';\n";

async function main(): Promise<void> {
  const providers = (
    await probe(`${IMPORT}export const providers: { [P in keyof ConnectEventPayloads]: 0 } = {};\n`)
  ).get('providers');
  if (!providers) throw new Error('Could not read the providers of ConnectEventPayloads.');

  const probes = providers.map(
    (provider, index) =>
      `export const p${index}: { [E in Extract<keyof ConnectEventPayloads[${JSON.stringify(provider)}], string>]: 0 } = {};`,
  );
  const keys = await probe(`${IMPORT}${probes.join('\n')}\n`);

  const entries = providers.map((provider, index) => {
    const types = keys.get(`p${index}`);
    if (!types?.length) throw new Error(`Could not read the event types of ${provider}.`);
    return `  ${JSON.stringify(provider)}: ${JSON.stringify([...types].sort())},`;
  });

  const code = `// This file is generated by \`pnpm generate:event-types\`. Do not edit it.

import type { ConnectEventPayloads } from './index.js';

/**
 * Every event type with a typed payload, by provider. A typed provider only
 * delivers these, so a delivered event's payload always has a type.
 */
export const connectEventTypes = {
${entries.join('\n')}
} as const satisfies { readonly [P in keyof ConnectEventPayloads]?: readonly Extract<keyof ConnectEventPayloads[P], string>[] };
`;
  await emit(OUT_FILE, code, `${providers.length} providers`);
  await writeFields(new Map(providers.map((provider, index) => [provider, [...keys.get(`p${index}`)!].sort()])));
}

async function emit(file: string, code: string, summary: string): Promise<void> {
  const previous = await readFile(file, 'utf8').catch(() => undefined);
  await writeFile(file, code);
  // Formatted the way the repo's `lint:format` check expects.
  const format = spawnSync('pnpm', ['exec', 'oxfmt', file], { stdio: 'inherit' });
  if (format.status !== 0) throw new Error(`oxfmt failed on ${file}`);
  const formatted = await readFile(file, 'utf8');
  console.info(`${previous === formatted ? 'unchanged' : 'wrote'} ${file.slice(PACKAGE_DIR.length + 1)} (${summary})`);
}

/**
 * The type-level walk behind `connectEventFields`: every path to a plain value (string, number or
 * boolean) in a payload, three objects deep (two for payloads too large for TypeScript to walk that far; an array element
 * sits at its array's depth). `[]` marks an array, so `issue.labels[].name` is the name of any label. Index signatures and link fields (`*_url`, `url`, `node_id`) are left out.
 */
const PATHS = `
type Scalar = string | number | boolean;
type Skip = \`\${string}_url\` | 'url' | 'node_id' | 'gravatar_id' | '_links' | 'template_repository' | 'permissions' | 'license' | 'security_and_analysis' | 'custom_properties' | 'enterprise' | 'installation';
type Known<T> = Exclude<keyof { [K in keyof T as string extends K ? never : number extends K ? never : K]: 0 } & string, Skip>;
type Join<K extends string, P extends string> = P extends '' ? K : P extends \`[]\${string}\` ? \`\${K}\${P}\` : \`\${K}.\${P}\`;
type Element<P extends string> = P extends '' ? '[]' : P extends \`[]\${string}\` ? \`[]\${P}\` : \`[].\${P}\`;
type Paths<T, Max extends number, D extends 0[] = []> = T extends Scalar ? ''
  : T extends readonly (infer U)[] ? Element<Paths<NonNullable<U>, Max, D>>
  : D['length'] extends Max ? never
  : T extends object ? { [K in Known<T>]: Join<K, Paths<NonNullable<T[K]>, Max, [...D, 0]>> }[Known<T>]
  : never;
`;

const FIELDS_FILE = join(PACKAGE_DIR, 'src/event-payloads/event-fields.generated.ts');

/** Writes `connectEventFieldTable`: each provider's field paths once, and each event type's as indexes into them. */
async function writeFields(typesByProvider: Map<string, string[]>): Promise<void> {
  const entries: string[] = [];
  for (const [provider, types] of typesByProvider) {
    const payloads = `ConnectEventPayloads[${JSON.stringify(provider)}]`;
    const byType = new Map<string, string[]>();
    // One tsc run per provider, one probe per event type, so a type too large to walk only costs itself a level.
    for (const depth of [3, 2]) {
      const pending = types.filter(type => !byType.has(type));
      if (pending.length === 0) break;
      const found = await probe(
        `${IMPORT}${PATHS}${pending.map((type, i) => `export const e${i}: { [K in Paths<${payloads}[${JSON.stringify(type)}], ${depth}> & string]: 0 } = {};`).join('\n')}\n`,
      ).catch(() => new Map<string, string[]>());
      pending.forEach((type, i) => {
        const paths = found.get(`e${i}`)?.filter(Boolean);
        if (paths?.length) byType.set(type, paths);
      });
    }
    const missing = types.filter(type => !byType.has(type));
    if (missing.length) throw new Error(`Could not read the fields of ${provider} events: ${missing.join(', ')}`);

    const fields = [...new Set([...byType.values()].flat())].sort();
    const position = new Map(fields.map((field, i) => [field, i]));
    const events = Object.fromEntries(
      [...byType.keys()].sort().map(type => [
        type,
        byType
          .get(type)!
          .map(f => position.get(f)!)
          .sort((a, b) => a - b),
      ]),
    );
    entries.push(
      `  ${JSON.stringify(provider)}: { fields: ${JSON.stringify(fields)}, events: ${JSON.stringify(events)} },`,
    );
  }

  const code = `// This file is generated by \`pnpm generate:event-types\`. Do not edit it.

/**
 * The fields each event type's payload can be filtered on, by provider: \`fields\` lists the
 * provider's paths once and \`events\` gives each type's as indexes into it. Read it through
 * \`connectEventFields\`.
 */
export const connectEventFieldTable: {
  readonly [provider: string]: { readonly fields: readonly string[]; readonly events: { readonly [eventType: string]: readonly number[] } };
} = {
${entries.join('\n')}
};
`;
  await emit(FIELDS_FILE, code, `${typesByProvider.size} providers`);
}

await main();
