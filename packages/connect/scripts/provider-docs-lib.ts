/**
 * Rendering and safe writing for Connect provider documentation. The CLI entry
 * point is generate-provider-docs.ts; tests drive these functions against
 * temporary directories so they never write into the working tree.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';

import type { Logo, McpProviderDocs, ProviderDocs, ToolProviderDocs } from './provider-docs-metadata.js';

export const REGENERATE_COMMAND = 'pnpm --filter @mastra/connect generate:provider-docs';
export const GENERATED_MARKER = `{/* Generated by packages/connect/scripts/generate-provider-docs.ts from provider-docs-metadata.ts. Do not edit. Regenerate with: ${REGENERATE_COMMAND} */}`;

/** Output locations, relative to the docs package root. */
export const REFERENCE_OUTPUT = 'src/content/en/reference/connect/providers.mdx';
export const INTEGRATIONS_DIR = 'src/content/en/integrations';
export const PARTIALS_DIR = 'src/components/connect/generated';

const MODEL = '__GATEWAY_OPENAI_MODEL_LUNA__';
const TOOLS_REFERENCE = '/reference/connect/tools';
const PROVIDER_TOOLSETS_REFERENCE = '/reference/connect/providers';

export interface Tool {
  id: string;
  desc: string;
}

export interface DocsMetadata {
  connectGuidePath: string;
  toolProviders: Record<string, ToolProviderDocs>;
  mcpProviders: Record<string, McpProviderDocs>;
}

export interface Output {
  /** Path relative to the docs package root. */
  path: string;
  content: string;
}

export function listToolProviders(providersDir: string, exclude: ReadonlySet<string>): string[] {
  return readdirSync(providersDir)
    .filter(p => {
      if (exclude.has(p)) return false;
      try {
        return statSync(join(providersDir, p, 'tools')).isDirectory();
      } catch {
        return false;
      }
    })
    .sort();
}

export function extractTools(providersDir: string, provider: string): Tool[] {
  const toolsDir = join(providersDir, provider, 'tools');
  const files = readdirSync(toolsDir)
    .filter(f => f.endsWith('.ts'))
    .sort();
  const tools: Tool[] = [];
  for (const f of files) {
    const src = readFileSync(join(toolsDir, f), 'utf8');
    const idMatch = src.match(/id:\s*'([^']+)'/);
    const descMatch = src.match(
      /id:\s*'[^']+',\s*\n\s*description:\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"|`((?:[^`\\]|\\.)*)`)/,
    );
    if (!idMatch) {
      console.error(`WARN: no id in ${provider}/${f}`);
      continue;
    }
    let desc = descMatch ? (descMatch[1] ?? descMatch[2] ?? descMatch[3] ?? '') : '';
    desc = desc.replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\s+/g, ' ').trim();
    // escape backslashes first, then pipes, for markdown tables
    desc = desc.replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
    tools.push({ id: idMatch[1]!, desc });
  }
  tools.sort((a, b) => a.id.localeCompare(b.id));
  return tools;
}

function logoJsx(logo: Logo | undefined): string {
  if (!logo) return '';
  const attrs = logo.src ? `src="${logo.src}"` : `slug="${logo.slug}"`;
  return `<ProviderLogo ${attrs}${logo.mono ? ' mono' : ''} /> `;
}

/** Default MDX heading slug (github-slugger style): lowercase, drop punctuation, spaces -> hyphens. */
export function headingSlug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, '')
    .replace(/ /g, '-');
}

function mcpProviderLinks(meta: DocsMetadata): string {
  const links = Object.values(meta.mcpProviders)
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(docs => `[${docs.name}](/integrations/${docs.canonicalPage.replace(/\.mdx$/, '')})`);
  if (links.length < 3) return links.join(' and ');
  return `${links.slice(0, -1).join(', ')}, and ${links.at(-1)}`;
}

export function renderReference(
  providers: string[],
  toolsByProvider: Record<string, Tool[]>,
  meta: DocsMetadata,
): string {
  let total = 0;
  let out = '';
  const tocRows: string[] = [];

  for (const provider of providers) {
    const tools = toolsByProvider[provider] ?? [];
    total += tools.length;
    const docs = meta.toolProviders[provider];
    const name = docs?.name ?? provider;
    tocRows.push(`| ${logoJsx(docs?.logo)}[${name}](#${headingSlug(name)}) | \`${provider}\` | ${tools.length} |`);
    out += `\n## ${name}\n\n`;
    out += `Provider ID: \`${provider}\` · ${tools.length} tools\n\n`;
    if (docs?.note) out += `:::note\n\n${docs.note}\n\n:::\n\n`;
    out += `| Tool | Description |\n| - | - |\n`;
    for (const t of tools) {
      out += `| \`${t.id}\` | ${t.desc || '—'} |\n`;
    }
  }

  const header = `---
title: "Reference: Provider toolsets | Connect"
description: "Documented provider toolsets in @mastra/connect: provider IDs and the full tool list for each listed provider."
packages:
  - "@mastra/connect"
---

${GENERATED_MARKER}

import { ProviderLogo } from '@site/src/components/connect/provider-logo';

# Provider toolsets

This page documents generated toolsets for ${providers.length} providers (${total} tools in this version of \`@mastra/connect\`). It isn't an exhaustive list of providers registered in the SDK or available in the platform catalog. [\`tools()\`](${TOOLS_REFERENCE}) exposes a provider's toolset when the project has an active connection for its provider ID.

Tool keys are stable identifiers of the form \`<provider>_<action>\` and are the values accepted by \`allowTools\` and \`disallowTools\`. Toolsets are versioned with the package: the exact list depends on the installed \`@mastra/connect\` version, and this page reflects the version it was generated from.

MCP providers (${mcpProviderLinks(meta)}) serve their tools from their hosted MCP servers at runtime and aren't listed here. See [MCP providers](${TOOLS_REFERENCE}#mcp-providers) for how \`tools()\` discovers them.

| Provider | Provider ID | Tools |
| - | - | - |
${tocRows.join('\n')}
`;

  return header + out;
}

function yamlString(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function camelCase(id: string): string {
  return id.replace(/[-_]+([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

function noteBlock(note: string | undefined): string {
  return note ? `:::note\n\n${note}\n\n:::\n\n` : '';
}

function admonitions(docs: ProviderDocs, mcp: boolean): string {
  const warning = docs.warning ? `:::warning\n\n${docs.warning}\n\n:::\n\n` : '';
  return warning + (mcp ? '' : noteBlock((docs as ToolProviderDocs).note));
}

function possessive(name: string): string {
  return name.endsWith('s') ? `${name}'` : `${name}'s`;
}

/** Escapes text for a single-quoted TypeScript string literal. */
function tsString(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function agentExample(id: string, docs: ProviderDocs): string {
  return `\`\`\`typescript title="src/mastra/agents/${id}-agent.ts"
import { Agent } from '@mastra/core/agent'
import { tools } from '@mastra/connect'

export const ${camelCase(id)}Agent = new Agent({
  id: '${id}-agent',
  name: ${tsString(`${docs.name} agent`)},
  instructions: ${tsString(`You help people ${docs.summary} in ${docs.name}.`)},
  model: '${MODEL}',
  tools: tools({ providers: ['${id}'] }),
})
\`\`\``;
}

function connectCommand(id: string): string {
  return `\`\`\`bash\nmastra connect add ${id}\n\`\`\``;
}

function toolsetSummary(id: string, docs: ToolProviderDocs, tools: Tool[]): string {
  const example = tools[0] ? `, with keys such as \`${tools[0].id}\`` : '';
  return `The agent gets ${tools.length} ${docs.name} tools${example}. See [${docs.name} tools](${PROVIDER_TOOLSETS_REFERENCE}#${headingSlug(docs.name)}) for the full list, and the [\`tools()\` parameters](${TOOLS_REFERENCE}#parameters) to restrict tools or require approval before a call runs.`;
}

function mcpSummary(id: string, docs: McpProviderDocs): string {
  return `Mastra discovers ${possessive(docs.name)} tools from its MCP server when the agent runs. The available tools depend on the server and the connected account, not on your \`@mastra/connect\` version. Tool keys start with \`${id}_\`.

To see which tools ${docs.name} provides, read the [${docs.mcpDocsLabel}](${docs.mcpDocsUrl}) documentation. To require approval before a call runs, see [MCP providers](${TOOLS_REFERENCE}#mcp-providers) in the \`tools()\` reference.`;
}

function pageIntro(docs: ProviderDocs, mcp: boolean): string {
  const how = mcp
    ? `${docs.name} serves these tools from a hosted Model Context Protocol (MCP) server.`
    : `Each tool call goes through the Mastra platform, which adds the connection's credential.`;
  return `Give agents tools to ${docs.summary} in ${docs.name} through Mastra Connect. ${how} Your application never stores ${docs.name} credentials.`;
}

export function renderProviderPage(id: string, docs: ProviderDocs, meta: DocsMetadata, tools?: Tool[]): string {
  const mcp = tools === undefined;
  const description = `Give Mastra agents ${docs.name} tools through Mastra Connect to ${docs.summary}.`;
  const usage = mcp ? mcpSummary(id, docs as McpProviderDocs) : toolsetSummary(id, docs, tools);
  const note = admonitions(docs, mcp);

  return `---
title: ${yamlString(`${docs.name} | ${docs.category}`)}
description: ${yamlString(description)}
packages:
  - "@mastra/connect"
---

${GENERATED_MARKER}

# ${docs.name}

${pageIntro(docs, mcp)}

## Connect

Before you start, complete the [Connect setup](${meta.connectGuidePath}#get-started) to install \`@mastra/connect\` and configure your platform project.

${note}### Connect an account

Run this command from the directory that contains your \`.env\` file:

${connectCommand(id)}

The CLI guides you through ${possessive(docs.name)} authorization and waits until the connection is active.

### Add tools to an agent

Pass [\`tools()\`](${TOOLS_REFERENCE}) to the agent and select the \`${id}\` provider:

${agentExample(id, docs)}

${usage}
`;
}

export function renderPartial(id: string, docs: ProviderDocs, tools?: Tool[]): string {
  const mcp = tools === undefined;
  const usage = mcp ? mcpSummary(id, docs as McpProviderDocs) : toolsetSummary(id, docs, tools);
  const note = admonitions(docs, mcp);
  const source = mcp ? ` from ${possessive(docs.name)} hosted Model Context Protocol (MCP) server` : '';

  return `${GENERATED_MARKER}

### Agent tools

Give agents tools${source} to ${docs.summary} in ${docs.name}.

Connect an account with the \`${id}\` provider ID. Run this command from the directory that contains your \`.env\` file:

${connectCommand(id)}

${note}Then pass [\`tools()\`](${TOOLS_REFERENCE}) to the agent and select the provider:

${agentExample(id, docs)}

${usage}
`;
}

const CANONICAL_PAGE = /^[a-z0-9-]+\/[a-z0-9-]+\.mdx$/;
const UNSAFE_PROSE = /[{}<>]/;

/** Rejects metadata that would produce unsafe, ambiguous, or incomplete outputs. */
export function validateMetadata(meta: DocsMetadata): void {
  const pages = new Map<string, string>();
  const all: Array<[string, ProviderDocs]> = [
    ...Object.entries(meta.toolProviders),
    ...Object.entries(meta.mcpProviders),
  ];
  for (const [id, docs] of all) {
    if (!CANONICAL_PAGE.test(docs.canonicalPage)) {
      throw new Error(`${id}: canonicalPage "${docs.canonicalPage}" must look like "<category>/<page>.mdx"`);
    }
    const owner = pages.get(docs.canonicalPage);
    if (owner) throw new Error(`${id}: canonicalPage "${docs.canonicalPage}" is already owned by ${owner}`);
    pages.set(docs.canonicalPage, id);
    if (docs.emit) {
      if (!docs.summary) throw new Error(`${id}: emitted providers need a summary`);
      if (docs.ownership === 'generated-page' && !docs.category) {
        throw new Error(`${id}: emitted generated pages need a sidebar category`);
      }
      if (UNSAFE_PROSE.test(docs.summary) || UNSAFE_PROSE.test(docs.name)) {
        throw new Error(`${id}: name and summary must not contain MDX syntax characters`);
      }
    }
  }
}

export function planOutputs(
  providers: string[],
  toolsByProvider: Record<string, Tool[]>,
  meta: DocsMetadata,
): Output[] {
  validateMetadata(meta);
  const outputs: Output[] = [{ path: REFERENCE_OUTPUT, content: renderReference(providers, toolsByProvider, meta) }];

  for (const [id, docs] of Object.entries(meta.toolProviders).sort(([a], [b]) => a.localeCompare(b))) {
    if (!docs.emit) continue;
    const tools = toolsByProvider[id];
    if (!tools) throw new Error(`${id}: emitted provider has no published toolset`);
    outputs.push(outputFor(id, docs, meta, tools));
  }
  for (const [id, docs] of Object.entries(meta.mcpProviders).sort(([a], [b]) => a.localeCompare(b))) {
    if (docs.emit) outputs.push(outputFor(id, docs, meta));
  }

  assertSafeOutputs(outputs);
  return outputs;
}

function outputFor(id: string, docs: ProviderDocs, meta: DocsMetadata, tools?: Tool[]): Output {
  if (docs.ownership === 'generated-page') {
    return {
      path: posix.join(INTEGRATIONS_DIR, docs.canonicalPage),
      content: renderProviderPage(id, docs, meta, tools),
    };
  }
  return { path: posix.join(PARTIALS_DIR, `${id}.mdx`), content: renderPartial(id, docs, tools) };
}

function isAllowedPath(path: string): boolean {
  if (path !== posix.normalize(path) || path.includes('..') || !path.endsWith('.mdx')) return false;
  if (path === REFERENCE_OUTPUT) return true;
  const dir = posix.dirname(path);
  if (dir === PARTIALS_DIR) return true;
  return posix.dirname(dir) === INTEGRATIONS_DIR;
}

export function assertSafeOutputs(outputs: Output[]): void {
  const seen = new Set<string>();
  for (const { path } of outputs) {
    if (!isAllowedPath(path)) throw new Error(`Refusing to write outside the allowed documentation outputs: ${path}`);
    if (seen.has(path)) throw new Error(`Duplicate documentation output path: ${path}`);
    seen.add(path);
  }
}

/** Writes outputs under docsRoot, refusing to overwrite files the generator doesn't own. */
export function writeOutputs(docsRoot: string, outputs: Output[]): string[] {
  assertSafeOutputs(outputs);
  for (const { path } of outputs) {
    const file = join(docsRoot, path);
    if (existsSync(file)) {
      if (!readFileSync(file, 'utf8').includes(GENERATED_MARKER)) {
        throw new Error(
          `Refusing to overwrite ${path}: it has no generator marker, so it may be handwritten. ` +
            `Change the provider's ownership in provider-docs-metadata.ts or move the file first.`,
        );
      }
    }
  }
  for (const { path, content } of outputs) {
    const file = join(docsRoot, path);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
  return outputs.map(o => o.path);
}
