// Mastra.HeadingSentenceCase sets `vocab: false`, so it doesn't see the
// project vocabulary and keeps its own copy in `exceptions:`. This check puts
// every term from accept.txt into a heading and runs the real rule on it, so a
// term added to accept.txt without a working heading exception fails here.
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const docsDir = join(dirname(fileURLToPath(import.meta.url)), '../..')
const stylesDir = join(docsDir, 'styles')
const localVale = join(docsDir, 'scripts/vale/bin', process.platform === 'win32' ? 'vale.exe' : 'vale')
const vale = process.env.VALE_BIN || (existsSync(localVale) ? localVale : 'vale')

const terms = readFileSync(join(stylesDir, 'config/vocabularies/Mastra/accept.txt'), 'utf8')
  .split('\n')
  .map(line => line.trim().replace(/^\(\?i\)/, ''))
  .filter(Boolean)

// Headings start on line 6 and are separated by a blank line, so heading i is
// on line 6 + 2i.
const firstLine = 6
const page = [
  '---',
  'title: Heading vocabulary check',
  'description: Generated by scripts/vale/check-heading-vocabulary.mjs.',
  '---',
  '',
  ...terms.flatMap(term => [`## Configure ${term} today`, '']),
].join('\n')

const workDir = mkdtempSync(join(tmpdir(), 'vale-heading-vocabulary-'))
try {
  const pagePath = join(workDir, 'src/content/en/docs/heading-vocabulary.mdx')
  mkdirSync(dirname(pagePath), { recursive: true })
  writeFileSync(pagePath, page)
  const configPath = join(workDir, '.vale.ini')
  writeFileSync(configPath, `StylesPath = ${stylesDir}\nVocab = Mastra\n\n[*.mdx]\nBasedOnStyles = Mastra\n`)

  const result = spawnSync(
    vale,
    [`--config=${configPath}`, '--filter=.Name=="Mastra.HeadingSentenceCase"', '--output=line', pagePath],
    { encoding: 'utf8' },
  )
  if (result.error) {
    throw new Error(
      `Couldn't run Vale (${vale}): ${result.error.message}. Run \`pnpm vale:download\`, or set VALE_BIN to an executable Vale binary.`,
      { cause: result.error },
    )
  }
  // Set exitCode instead of calling process.exit() so `finally` removes workDir.
  const flagged = [
    ...new Set(
      [...result.stdout.matchAll(/^.+?\.mdx:(\d+):/gm)].map(match => terms[(Number(match[1]) - firstLine) / 2]),
    ),
  ]
  if (flagged.length > 0) {
    console.error(
      'Mastra.HeadingSentenceCase flags these accept.txt terms in headings. Add an exception for each to styles/Mastra/HeadingSentenceCase.yml:',
    )
    for (const term of flagged) console.error(`  - ${term}`)
    process.exitCode = 1
  } else if (result.status !== 0) {
    process.stderr.write(result.stdout + result.stderr)
    process.exitCode = result.status ?? 1
  } else {
    console.log(`Mastra.HeadingSentenceCase accepts all ${terms.length} accept.txt terms in headings.`)
  }
} finally {
  rmSync(workDir, { recursive: true, force: true })
}
