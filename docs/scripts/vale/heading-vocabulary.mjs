// Mastra.HeadingSentenceCase sets `vocab: false` (see the comment in the rule),
// so it keeps its own copy of the accept.txt terms in `exceptions:`. That copy
// lives between the markers below and is generated from accept.txt, so the two
// can't drift: `pnpm check` reports a stale copy and `pnpm check --fix`
// rewrites it.

export const RULE_FILE = 'styles/Mastra/HeadingSentenceCase.yml'
export const ACCEPT_FILE = 'styles/config/vocabularies/Mastra/accept.txt'

const BEGIN = '  # BEGIN accept.txt terms. Generated by `pnpm check --fix`: edit accept.txt instead.'
const END = '  # END accept.txt terms.'

/** accept.txt terms without their `(?i)` prefix. */
export function acceptTerms(acceptTxt) {
  return acceptTxt
    .split('\n')
    .map(line => line.trim())
    .filter(line => line && !line.startsWith('#'))
    .map(line => line.replace(/^\(\?i\)/, ''))
}

/**
 * The rule file with the generated block replaced by the current accept.txt terms.
 * The `(?i)` prefixes are dropped on purpose: a case-insensitive exception leaks to
 * the rest of the rule's expression, so a short term like "ID" would excuse every
 * word that contains it.
 */
export function renderHeadingVocabulary(ruleYaml, acceptTxt) {
  const start = ruleYaml.indexOf(BEGIN)
  const end = ruleYaml.indexOf(END)
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${RULE_FILE} is missing the "BEGIN accept.txt terms" / "END accept.txt terms" markers`)
  }
  const entries = acceptTerms(acceptTxt).map(term => `  - '${term.replaceAll("'", "''")}'`)
  return ruleYaml.slice(0, start) + [BEGIN, ...entries, ''].join('\n') + ruleYaml.slice(end)
}
